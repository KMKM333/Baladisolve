#!/usr/bin/env node
// Import citizen reports from Baladi Map into Manāra's PROJECTS array.
//
// Runs at dev time, never in the browser: it reads Baladi's public pages, maps
// the reports onto Manāra's own shape, and rewrites the block between the two
// markers in index.html. Output is committed, so the live site never calls
// baladimap.com — no CORS, no API key, and nothing scraping a partner in
// production. robots.txt allows both pages it reads.
//
//   node scripts/import-baladi.mjs             # 20 reports, photos preferred
//   node scripts/import-baladi.mjs --limit 60
//   node scripts/import-baladi.mjs --pages 15  # 12 reports per page
//
// Two sources, joined on id, because neither is complete on its own:
//   /en/issues?page=N  description, photo_urls, created_at, governorate
//   /en/map            latitude and longitude
//
// Re-running replaces the block rather than appending to it.

import fs from 'node:fs';

const LIST = (p) => `https://www.baladimap.com/en/issues?page=${p}`;
const MAP = 'https://www.baladimap.com/en/map';
const UA = { 'user-agent': 'Manara-import/1.0 (+partner integration)' };
const START = '  /* ===== BALADI IMPORT START — generated by scripts/import-baladi.mjs ===== */';
const END = '  /* ===== BALADI IMPORT END ===== */';
const FIRST_ID = 1001;

const arg = (f, d) => { const i = process.argv.indexOf(f); return i > -1 ? parseInt(process.argv[i + 1], 10) : d; };
const LIMIT = arg('--limit', 20);
const PAGES = arg('--pages', 6);

const TYPE = {
  roads: 'Public Roads', waste: 'Environment & Waste', electricity: 'Public Lighting',
  water: 'Water & Sanitation', sewage: 'Water & Sanitation',
  public_spaces: 'Public Space & Land Use', other: 'Public Space & Land Use',
};
const URGENCY = { critical: 'Critical', high: 'High', medium: 'Medium', low: 'Low' };
// Baladi's governorate names line up with Manāra's GOVS one for one.
const GOV = {
  'Akkar': 'akkar', 'North': 'north', 'Keserwan-Jbeil': 'keserwan', 'Keserwan': 'keserwan',
  'Baalbek-Hermel': 'baalbek', 'Beirut': 'beirut', 'Mount Lebanon': 'mtlebanon',
  'Beqaa': 'bekaa', 'Bekaa': 'bekaa', 'Nabatieh': 'nabatieh', 'South': 'south',
};

const esc = (v) => String(v ?? '').replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\s+/g, ' ').trim();

// Pull the RSC flight payload out of a Next.js page.
async function flight(url) {
  const html = await fetch(url, { headers: UA }).then((r) => {
    if (!r.ok) throw new Error(`${url} returned ${r.status}`);
    return r.text();
  });
  return [...html.matchAll(/self\.__next_f\.push\(\[1,("(?:[^"\\]|\\.)*")\]\)/g)]
    .map((m) => JSON.parse(m[1])).join('');
}
// Every {"id":"<uuid>","title": … } object in a payload, brace-matched.
function objects(buf) {
  const out = [];
  for (const m of buf.matchAll(/\{"id":"[0-9a-f-]{36}","title":/g)) {
    let d = 0;
    for (let i = m.index; i < buf.length; i++) {
      if (buf[i] === '{') d++;
      else if (buf[i] === '}' && --d === 0) {
        try { out.push(JSON.parse(buf.slice(m.index, i + 1))); } catch { /* partial chunk */ }
        break;
      }
    }
  }
  return out;
}

const reports = new Map();
for (let p = 1; p <= PAGES; p++) {
  for (const r of objects(await flight(LIST(p)))) if (!reports.has(r.id)) reports.set(r.id, r);
}
// Coordinates only exist on the map page.
const coords = new Map();
for (const r of objects(await flight(MAP))) if (r.latitude) coords.set(r.id, [r.latitude, r.longitude]);

// Prefer reports that carry a photo, then spread across categories so a sample
// is not simply the roads backlog, then most-confirmed first within each.
function pick(n) {
  const usable = [...reports.values()].filter((r) => r.title && coords.has(r.id));
  const byCat = new Map();
  for (const r of usable) {
    if (!byCat.has(r.category)) byCat.set(r.category, []);
    byCat.get(r.category).push(r);
  }
  for (const list of byCat.values()) {
    list.sort((a, b) =>
      ((b.photo_urls?.length ? 1 : 0) - (a.photo_urls?.length ? 1 : 0)) ||
      ((b.affected_count || 0) - (a.affected_count || 0)) || a.id.localeCompare(b.id));
  }
  const cats = [...byCat.keys()].sort();
  const out = [];
  for (let round = 0; out.length < n; round++) {
    let added = false;
    for (const c of cats) {
      const r = byCat.get(c)[round];
      if (r) { out.push(r); added = true; if (out.length === n) break; }
    }
    if (!added) break;
  }
  return out;
}

function toRecord(r, i) {
  const conf = r.affected_count || 0;
  const muni = r.municipalities || {};
  const locality = muni.name_en || r.location_name || 'Lebanon';
  const gov = GOV[muni.governorate] || 'mtlebanon';
  const ref = 'BM-' + r.id.slice(0, 8).toUpperCase();
  const [lat, lng] = coords.get(r.id);
  const when = r.created_at ? new Date(r.created_at).toLocaleDateString('en-GB', { day: 'numeric', month: 'short' }) : '—';
  // The reporter's own words, then a plain statement of what has not happened.
  // Nothing about the funding side is invented, because none of it exists yet.
  const desc = (r.description ? esc(r.description) + ' ' : '')
    + `Reported on Baladi Map from ${esc(locality)}`
    + (conf ? `, and confirmed by ${conf} resident${conf === 1 ? '' : 's'}` : '')
    + '. Not yet certified, costed or open for funding.';
  const photo = r.photo_urls && r.photo_urls[0];
  return `  {id:${FIRST_ID + i}, title:'${esc(r.title)}', type:'${TYPE[r.category] || TYPE.other}', gov:'${gov}', `
    + `locality:'${esc(locality)}', size:'small', goal:null, raised:0, status:'proposed', urgency:'${URGENCY[r.severity] || 'Medium'}',\n`
    + `   partner:'Not yet assigned', org:'${esc(locality)} — reporting community', corridor:null, audienceTags:['locals'],\n`
    + `   certifyingBody:null, certStatus:'pending', source:'baladi', sourceId:'${r.id}',\n`
    + `   sourceUrl:'https://www.baladimap.com/en/issues/${r.id}',\n`
    + `   coords:[${lat},${lng}],${photo ? `\n   photo:'${photo}',` : ''}\n`
    + `   metrics:[{label:'Residents confirmed', value:${conf}}],\n`
    + `   timeline:{start:'reported ${when}', target:'TBD — awaiting certification', schedule:'early', scheduleLabel:'Not yet certified'},\n`
    + `   originReport:{ref:'${ref}', confirmed:${conf}}, beneficiaries:${conf}, daysToMilestone:null, interest:${conf}, interestable:true,\n`
    + `   desc:'${desc}',\n`
    + `   ledger:[{t:'Reported on Baladi Map', d:'${when}', meta:'${conf} resident${conf === 1 ? '' : 's'} confirmed · not yet certified', ref:'${ref}', state:'pending'}],\n`
    + `   donations:[],\n`
    + `   comments:[]},`;
}

const chosen = pick(LIMIT);
const block = [START, ...chosen.map(toRecord), END].join('\n');

const file = 'index.html';
let src = fs.readFileSync(file, 'utf8');
const rx = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
if (src.includes(START)) {
  src = src.replace(new RegExp(rx(START) + '[\\s\\S]*?' + rx(END)), block);
} else {
  const i = src.indexOf('\n];\n', src.indexOf('const PROJECTS = ['));
  if (i === -1) throw new Error('could not find the end of PROJECTS');
  src = src.slice(0, i) + '\n' + block + src.slice(i);
}
fs.writeFileSync(file, src);

const tally = (f) => [...chosen.reduce((m, x) => m.set(f(x), (m.get(f(x)) || 0) + 1), new Map())]
  .sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(' · ');
console.log(`Baladi: ${reports.size} reports read across ${PAGES} pages, ${coords.size} with coordinates`);
console.log(`Imported ${chosen.length} as ids ${FIRST_ID}–${FIRST_ID + chosen.length - 1}`);
console.log('  categories   ', tally((x) => x.category));
console.log('  severities   ', tally((x) => x.severity));
console.log('  governorates ', tally((x) => (x.municipalities || {}).governorate));
console.log('  with photo   ', chosen.filter((x) => x.photo_urls?.length).length, `of ${chosen.length}`);
console.log('  with text    ', chosen.filter((x) => x.description).length, `of ${chosen.length}`);
console.log('  confirmations', chosen.reduce((a, x) => a + (x.affected_count || 0), 0));
